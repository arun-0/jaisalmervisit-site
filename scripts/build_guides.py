"""Build the travel guides, their links on the homepage, and the XML sitemap."""
import argparse
from dataclasses import dataclass
from html import escape
import json
from pathlib import Path
import re
from string import Template
import sys
import tomllib
from urllib.parse import urlsplit
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
HOME_CANONICAL = re.search(r'<link rel="canonical" href="(https://[^/"]+)/">',
                           (PUBLIC / "index.html").read_text("utf-8"))
if HOME_CANONICAL is None:
    raise ValueError("The homepage needs an absolute HTTPS canonical URL")
ORIGIN = HOME_CANONICAL[1]
GROUPS = {
    "places": ("Place guides", "explore", "TouristAttraction"),
    "itineraries": ("Itineraries", "plan", "TouristTrip"),
    "things-to-do": ("Activity guides", "things-to-do", "Article"),
}
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
MARKER = "<!-- Generated by scripts/build_guides.py -->"
DEFAULT_IMAGE = "/og-image.jpg"
DEFAULT_ALT = "Jaisalmer Fort lit up at dusk above the old city"


@dataclass
class Guide:
    group: str
    slug: str
    meta: dict
    body: str

    @property
    def path(self):
        return f"/{self.group}/{self.slug}"

    @property
    def title(self):
        return self.meta["title"]


def valid_url(value):
    if not isinstance(value, str) or re.search(r"[\s\\\x00-\x1f]", value):
        return False
    url = urlsplit(value)
    return (url.scheme == "https" and bool(url.hostname) and not url.username
            or value.startswith("/") and not value.startswith("//"))


def load_guide(path):
    slug = path.stem
    if not SLUG.fullmatch(slug):
        raise ValueError(f"Use lowercase words and hyphens in {path.name}")
    header, body = path.read_text(encoding="utf-8").removeprefix("+++\n").split("\n+++\n", 1)
    meta = tomllib.loads(header)
    for key in ("title", "description"):
        if not isinstance(meta.get(key), str) or not meta[key].strip():
            raise ValueError(f"{path.name} needs a {key}")
    if "app_id" in meta and not SLUG.fullmatch(meta["app_id"]):
        raise ValueError(f"Invalid app_id in {path.name}")
    if "image" in meta and (not valid_url(meta["image"]) or not meta.get("image_alt", "").strip()):
        raise ValueError(f"{path.name} needs a valid image and its description")
    if "lat" in meta or "lng" in meta:
        if not (-90 <= meta["lat"] <= 90 and -180 <= meta["lng"] <= 180):
            raise ValueError(f"Invalid coordinates in {path.name}")
    return Guide(path.parent.name, slug, meta, body.strip())


def inline(text):
    """Plain text and ordinary Markdown links. Escape all editor-supplied markup."""
    parts = []
    end = 0
    for link in re.finditer(r"\[([^\]\n]+)\]\(([^()\s]+)\)", text):
        label, href = link.groups()
        if not valid_url(href):
            raise ValueError(f"Invalid link destination {href!r}")
        parts.extend([escape(text[end:link.start()]), f'<a href="{escape(href)}">{escape(label)}</a>'])
        end = link.end()
    return "".join(parts) + escape(text[end:])


def sections(markdown):
    """Group headings, paragraphs and bullet lists, keeping section boundaries for ad placement."""
    output = []
    for line in re.split(r"\n\s*\n", markdown):
        if line.startswith("## "):
            if "\n" in line:
                raise ValueError("Leave a blank line after each heading")
            output.append([f"<h2>{inline(line[3:])}</h2>"])
            continue
        if not output:
            raise ValueError("Start the guide with a second-level heading")
        if line.startswith("### "):
            html = f"<h3>{inline(line[4:])}</h3>"
        elif line.startswith("- "):
            items = line.splitlines()
            if any(not item.startswith("- ") for item in items):
                raise ValueError("Start each list item with a dash and space")
            html = "<ul>" + "".join(f"<li>{inline(item[2:])}</li>" for item in items) + "</ul>"
        else:
            html = f"<p>{inline(' '.join(line.splitlines()))}</p>"
        output[-1].append(html)
    if not output:
        raise ValueError("A guide needs at least one section")
    return ["<section>" + "\n".join(block) + "</section>" for block in output]


def asset(kind, name, extension):
    matches = list((PUBLIC / "assets" / kind).glob(f"{name}.????????.{extension}"))
    if len(matches) != 1:
        raise ValueError(f"Expected one hashed {name} asset, found {len(matches)}")
    return "/" + matches[0].relative_to(PUBLIC).as_posix()


def advertising():
    slots = tomllib.loads((ROOT / "content/advertising.toml").read_text("utf-8"))["slots"]
    if slots and (len(slots) not in (2, 3) or any(not re.fullmatch(r"\d{10}", s) for s in slots)):
        raise ValueError("Use two or three confirmed ten-digit AdSense display unit IDs")
    sellers = (PUBLIC / "ads.txt").read_text("utf-8")
    publisher = re.search(r"(?m)^google\.com,\s*(pub-\d+),\s*DIRECT\b", sellers)
    if not publisher:
        raise ValueError("Missing Google publisher in ads.txt")
    return "ca-" + publisher[1], slots


def place_ads(blocks, words, publisher, slots):
    limit = 3 if words >= 1000 else 2 if words >= 600 else 0
    if not slots or not limit or len(blocks) < 3:
        return "", blocks
    positions = [0, len(blocks) // 2, len(blocks)]
    merged = blocks.copy()
    for pos, slot in reversed(list(zip(positions, slots[:limit]))):
        merged.insert(pos, f'<aside class="guide-ad" aria-label="Advertisement">Advertisement'
                      f'<ins class="adsbygoogle" data-ad-client="{publisher}" data-ad-slot="{slot}" '
                      'data-ad-format="auto" data-full-width-responsive="true"></ins>'
                      '<script>(window.adsbygoogle = window.adsbygoogle || []).push({});</script></aside>')
    loader = (f'<script async crossorigin="anonymous" '
              f'src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client={publisher}"></script>')
    return loader, merged


def guide_html(guide, by_path, template, assets, publisher, slots):
    meta = guide.meta
    section, anchor, schema_type = GROUPS[guide.group]
    canonical = ORIGIN + guide.path
    image = meta.get("image", DEFAULT_IMAGE)
    share_image = ORIGIN + image if image.startswith("/") else image
    share_alt = meta.get("image_alt", DEFAULT_ALT)
    entity = {"@type": schema_type, "@id": canonical + "#subject", "name": guide.title,
              "description": meta["description"], "url": canonical, "image": share_image}
    if schema_type == "Article":
        entity.update(headline=guide.title, inLanguage="en", author={"@type": "Organization", "name": "Jaisalmer Visit"})
    if "lat" in meta:
        entity["geo"] = {"@type": "GeoCoordinates", "latitude": meta["lat"], "longitude": meta["lng"]}
    graph = [entity]
    faq_html = ""
    faqs = meta.get("faq", [])
    if faqs:
        questions = []
        answers = []
        for item in faqs:
            q, a = item["question"], item["answer"]
            questions.append({"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}})
            answers.append(f"<h3>{escape(q)}</h3><p>{escape(a)}</p>")
        graph.append({"@type": "FAQPage", "@id": canonical + "#questions", "mainEntity": questions})
        faq_html = '<section id="questions"><h2>Common questions</h2>' + "".join(answers) + "</section>"
    related = [by_path[path] for path in meta.get("related", [])]
    related_html = ""
    if related:
        links = "".join(f'<li><a href="{item.path}">{escape(item.title)}</a></li>' for item in related)
        related_html = f"<section><h2>Plan the rest of your visit</h2><ul>{links}</ul></section>"
    section_url = "/#" + anchor
    app_id = meta.get("app_id")
    action_label, action_url = {
        "places": ("Open the tourist map", "/#map/" + (app_id or "")),
        "itineraries": ("Open the trip planner", "/#plan?trip=" + (app_id or "")),
        "things-to-do": ("Explore this activity", "/#things-to-do?activity=" + (app_id or "")),
    }[guide.group]
    if not app_id:
        action_label, action_url = "Explore " + section.lower(), section_url
    photo = ""
    if "image" in meta:
        photo = (f'<img class="guide-photo" src="{escape(image)}" alt="{escape(share_alt)}" '
                 'width="960" height="540" decoding="async" fetchpriority="high">')
    loader, blocks = place_ads(sections(guide.body), len(guide.body.split()), publisher, slots)
    schema = json.dumps({"@context": "https://schema.org", "@graph": graph},
                        ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    return template.substitute(
        assets, title=escape(guide.title), description=escape(meta["description"]), canonical=canonical,
        share_image=escape(share_image), share_alt=escape(share_alt), schema=schema, photo=photo,
        section_url=section_url, section_label=section, action_label=action_label, action_url=escape(action_url),
        body="\n".join(blocks), faq_html=faq_html, related_html=related_html, ad_script=loader)


def homepage(guides):
    html = (PUBLIC / "index.html").read_text("utf-8")
    for group, (label, _, _) in GROUPS.items():
        start, end = f"<!-- guides:{group} -->", f"<!-- /guides:{group} -->"
        if html.count(start) != 1 or html.count(end) != 1:
            raise ValueError(f"Missing link markers for {group} in index.html")
        before, rest = html.split(start)
        _, after = rest.split(end)
        entries = sorted((g for g in guides if g.group == group), key=lambda g: g.title.casefold())
        links = "\n".join(f'      <li><a href="{g.path}">{escape(g.title)}</a></li>' for g in entries)
        html = (before + start + f'\n  <details class="guide-links"><summary>{label}</summary>\n'
                + f'    <ul class="guide-link-list">\n{links}\n    </ul>\n  </details>\n  ' + end + after)
    return html


def sitemap(paths):
    root = ET.Element("urlset", xmlns="http://www.sitemaps.org/schemas/sitemap/0.9")
    for path in paths:
        ET.SubElement(ET.SubElement(root, "url"), "loc").text = ORIGIN + path
    ET.indent(root)
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"


def build(check):
    guides = [load_guide(p) for group in GROUPS for p in sorted((ROOT / "content" / group).glob("*.md"))]
    if set(g.group for g in guides) != set(GROUPS):
        raise ValueError("A guide category is empty")
    by_path = {guide.path: guide for guide in guides}
    template = Template((ROOT / "templates/guide.html").read_text("utf-8"))
    assets = dict(site_css=asset("css", "site", "css"), guide_css=asset("css", "guides", "css"),
                  config_js=asset("js", "firebase-config", "js"), analytics_js=asset("js", "analytics", "js"))
    publisher, slots = advertising()
    outputs = {}
    for guide in guides:
        out = PUBLIC / (guide.path[1:] + ".html")
        outputs[out] = guide_html(guide, by_path, template, assets, publisher, slots)
    outputs[PUBLIC / "index.html"] = homepage(guides)
    outputs[PUBLIC / "sitemap.xml"] = sitemap(["/", "/privacy", *by_path])

    changed = []
    for path, data in outputs.items():
        if path.is_file():
            current = path.read_text("utf-8")
            if current == data:
                continue
            if path.parent.name in GROUPS and MARKER not in current:
                raise ValueError(f"Hand-written file at {path}")
        changed.append(path)
        if not check:
            path.parent.mkdir(exist_ok=True)
            path.write_text(data, encoding="utf-8", newline="\n")
    for group in GROUPS:
        for path in (PUBLIC / group).glob("*.html"):
            if path not in outputs and MARKER in path.read_text("utf-8"):
                changed.append(path)
                if not check:
                    path.unlink()
    if check and changed:
        raise SystemExit("Rebuild guides before deploying:\n" + "\n".join(str(p.relative_to(ROOT)) for p in changed))
    print(f"{len(guides)} guides, {len(guides) + 2} sitemap URLs, {len(changed)} files updated.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if tracked output needs a rebuild")
    try:
        build(parser.parse_args().check)
    except (KeyError, ValueError) as error:
        sys.exit(f"Guide data error: {error}")
